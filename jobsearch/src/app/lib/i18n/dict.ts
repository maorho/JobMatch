export type Key = keyof typeof he;
const en: Record<Key, string> = {
  ...baseEn, ...dashboard.en, ...settings.en, ...widgets.en, ...interview.en, ...practice.en,
  ...resume.en, ...pages.en, ...legal.en, ...admin.en, ...recruiter.en,
};

export const DICT: Record<Lang, Record<Key, string>> = { he, en };

export function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w[\w-]*)\}/g, (_, k) => (vars[k] === undefined || vars[k] === null ? `{${k}}` : String(vars[k])));
}

/** Translate outside React (server components, hub pages): the language is passed in. */
export const translate = (lang: Lang, key: Key, vars?: Record<string, string | number>) => format(DICT[lang][key] ?? DICT.he[key] ?? key, vars);
export const dirOf = (lang: Lang) => (lang === "he" ? "rtl" : "ltr");
